import { explicitThemeFeel, parseModelFeel, type ThemeFeel } from "./theme-explorer.js";

export type ModelState = { phase: "off" | "loading" | "ready" | "thinking" | "error"; message: string; answer?: string };
export interface ThemeWorkerPort {
  postMessage(message: unknown): void;
  terminate(): void;
  onmessage: ((event: {data: {type: string; id?: number; answer?: string; text?: string; percent?: number}}) => void) | null;
  onerror: ((event: {message?: string}) => void) | null;
}
/** Owns request ordering and recovery separately from React and inference. */
export class ThemeAIClient {
  private worker: ThemeWorkerPort | null = null;
  private serial = 0;
  private pending: { id: number; prompt: string } | null = null;
  private ready = false;
  private timer: ReturnType<typeof setTimeout> | undefined;
  constructor(private factory: () => ThemeWorkerPort, private state: (state: ModelState) => void, private result: (feel: ThemeFeel) => void, private timeout = 120_000, private profile: "compact" | "desktop" = "desktop") {}
  private arm() {
    clearTimeout(this.timer);
    this.timer = setTimeout(()=>this.fail("Local AI timed out. Your musical result is still available. Retry or continue without AI."),this.timeout);
  }
  private fail(message: string) {
    this.dispose();
    this.state({phase:"error",message});
  }
  enable() {
    if (this.worker) return;
    this.state({phase:"loading",message:this.profile==="compact" ? "Downloading compact local AI · model files about 140 MB" : "Downloading local AI · first use needs internet (about 520 MB)"});
    try {
      const worker = this.factory(); this.worker = worker; this.arm();
      worker.onerror = event=>{if(worker===this.worker)this.fail(`Local AI could not start: ${event.message || "browser worker failed"}. Chords still work without AI.`);};
      worker.onmessage = ({data})=>{
        if (worker !== this.worker) return;
        if (data.type === "error") { this.fail(`Local AI unavailable: ${data.text || "model failed"}. Chords still work without AI.`); return; }
        if (data.type === "progress" || data.type === "status") {
          this.arm(); this.state({phase:"loading",message:data.type === "progress" ? `Downloading local AI · ${data.percent}% of model file` : data.text || "Preparing local AI…"});
        }
        if (data.type === "ready") {
          this.ready = true; clearTimeout(this.timer);
          this.state({phase:"ready",message:"Local AI ready · prompts stay on this device"});
          if(this.pending) this.send();
        }
        if (data.type === "result" && this.pending?.id === data.id) {
          const cue=explicitThemeFeel(this.pending!.prompt);
          clearTimeout(this.timer); this.pending=null;
          const suggested=parseModelFeel(data.answer || "");
          const feel=suggested ? cue ?? suggested : null;
          if(feel) this.result(feel);
          this.state({phase:"ready",answer:(data.answer||"").slice(0,500),message:feel ? cue && cue!==suggested ? `AI suggested ${suggested} · kept your explicit theme cue: ${cue}` : "Local AI interpreted your theme · chords generated by music theory" : "AI response was unclear · kept the instant musical result"});
        }
      };
      worker.postMessage({type:"load",profile:this.profile});
    } catch(error) { this.fail(`Local AI could not start: ${error instanceof Error ? error.message : "unsupported browser"}. Chords still work without AI.`); }
  }
  analyze(prompt: string) {
    this.invalidate();
    if(!this.worker || !prompt.trim()) return;
    this.pending={id:this.serial,prompt:prompt.trim().slice(0,400)};
    if(this.ready) this.send();
  }
  private send() {
    if(!this.pending) return;
    this.arm(); this.state({phase:"thinking",message:"Interpreting your theme locally · instant chords are ready to play"});
    this.worker?.postMessage({type:"analyze",...this.pending});
  }
  invalidate() {
    this.serial++; this.pending=null;
    if(this.ready) {clearTimeout(this.timer);this.state({phase:"ready",message:"Local AI ready · prompts stay on this device"});}
  }
  dispose() {
    clearTimeout(this.timer); this.worker?.terminate(); this.worker=null; this.ready=false; this.invalidate();
  }
}
